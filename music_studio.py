import yt_dlp, os, glob

def p1_download(url: str, fmt: str = 'mp3', cookies_path: str = '') -> dict:
    # Validation d'URL : limite aux domaines Instagram / YouTube en http(s)
    # (évite qu'une URL arbitraire — file://, hôte interne… — soit passée à yt-dlp).
    from urllib.parse import urlparse
    parsed = urlparse(url)
    allowed = ('instagram.com', 'youtube.com', 'youtu.be')
    host = (parsed.hostname or '').lower()
    if parsed.scheme not in ('http', 'https') or not any(host == d or host.endswith('.' + d) for d in allowed):
        return {'success': False, 'path': '', 'title': '',
                'error': 'URL non autorisée (Instagram / YouTube en http(s) uniquement).'}
    out_dir = './downloads'
    os.makedirs(out_dir, exist_ok=True)
    # Garde-fous communs : borne la taille (évite de saturer le disque de la VM
    # avec une longue vidéo) et restreint les noms de fichiers (titres exotiques).
    MAX_FILESIZE = 200 * 1024 * 1024  # 200 Mo
    # `max_filesize` ne s'applique que si le format ANNONCE sa taille ; beaucoup de
    # flux (HLS, certains Reels) ne la déclarent pas. Ce hook borne réellement le
    # disque en interrompant dès que la taille (déclarée OU déjà téléchargée) dépasse.
    def _abort_if_too_big(d):
        if d.get('status') != 'downloading':
            return
        total = d.get('total_bytes') or d.get('total_bytes_estimate') or 0
        if total > MAX_FILESIZE or d.get('downloaded_bytes', 0) > MAX_FILESIZE:
            raise Exception('Fichier trop volumineux (> 200 Mo) — téléchargement interrompu.')
    if fmt == 'mp4':
        ydl_opts = {
            'format': 'bestvideo+bestaudio/best',
            'outtmpl': f'{out_dir}/%(title)s.%(ext)s',
            'merge_output_format': 'mp4',
            'restrictfilenames': True,
            'max_filesize': MAX_FILESIZE,
            'progress_hooks': [_abort_if_too_big],
            'noplaylist': True,
            'quiet': True, 'no_warnings': True,
        }
    else:
        ydl_opts = {
            'format': 'bestaudio/best',
            'outtmpl': f'{out_dir}/%(title)s.%(ext)s',
            'restrictfilenames': True,
            'max_filesize': MAX_FILESIZE,
            'progress_hooks': [_abort_if_too_big],
            'noplaylist': True,
            'postprocessors': [{
                'key': 'FFmpegExtractAudio',
                'preferredcodec': fmt,
                'preferredquality': '320' if fmt == 'mp3' else '0',
            }],
            'quiet': True, 'no_warnings': True,
        }
    # isfile : refuse répertoires / chemins spéciaux ; .txt : restreint à un vrai
    # fichier cookies (réduit la lecture de fichiers locaux arbitraires).
    if cookies_path and os.path.isfile(cookies_path) and cookies_path.lower().endswith('.txt'):
        ydl_opts['cookiefile'] = cookies_path
    try:
        with yt_dlp.YoutubeDL(ydl_opts) as ydl:
            info = ydl.extract_info(url, download=True)
            title = info.get('title', 'audio')
            base = ydl.prepare_filename(info)
        # Après extraction audio l'extension devient `fmt` (mp3/wav) ; pour le
        # mp4 c'est déjà la bonne. On cible le fichier exact de CE téléchargement
        # au lieu du plus récent du dossier (qui pouvait être un ancien fichier).
        expected = os.path.splitext(base)[0] + f'.{fmt}'
        if os.path.exists(expected):
            return {'success': True, 'path': expected, 'title': title, 'error': ''}
        # Repli : fichier le plus récent du bon format.
        files_found = sorted(glob.glob(f'{out_dir}/*.{fmt}'), key=os.path.getmtime, reverse=True)
        if files_found:
            return {'success': True, 'path': files_found[0], 'title': title, 'error': ''}
        return {'success': False, 'path': '', 'title': '', 'error': 'Fichier introuvable après téléchargement'}
    except Exception as e:
        return {'success': False, 'path': '', 'title': '', 'error': str(e)}

def p1_get_audio_files(audio_only: bool = True):
    # Les dropdowns d'identification (P2) et de complétion (P3) ne doivent lister
    # que des fichiers décodables par torchaudio : on exclut les .mp4 (conteneur
    # vidéo non décodable tel quel) par défaut.
    patterns = ['*.mp3', '*.wav'] if audio_only else ['*.mp3', '*.wav', '*.mp4']
    f = []
    for pat in patterns:
        f += glob.glob(f'./downloads/{pat}')
    return sorted(os.path.basename(x) for x in f)

