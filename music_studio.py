# Cache de décodage : torchaudio.load est coûteux ; on évite de re-décoder le
# même fichier entre l'identification (Partie 2) et la complétion (Partie 3).
# LRU borné aux 2 derniers fichiers : alterner entre deux pistes ne force plus
# un re-décodage à chaque bascule (mémoire restant bornée).
from collections import OrderedDict
_AUDIO_RAW_CACHE = OrderedDict()
_AUDIO_RAW_MAX = 2
def _load_raw(path: str):
    st = os.stat(path)
    sig = (st.st_mtime, st.st_size)      # mtime + taille : invalide le cache même si un
    cached = _AUDIO_RAW_CACHE.get(path)  # fichier est remplacé en gardant le même mtime
    if cached and cached[0] == sig:
        _AUDIO_RAW_CACHE.move_to_end(path)
        return cached[1], cached[2]
    waveform, sr = torchaudio.load(path)
    _AUDIO_RAW_CACHE[path] = (sig, waveform, sr)
    _AUDIO_RAW_CACHE.move_to_end(path)
    while len(_AUDIO_RAW_CACHE) > _AUDIO_RAW_MAX:
        _AUDIO_RAW_CACHE.popitem(last=False)
    return waveform, sr

def _to_mono(path: str, target_sr: int, max_seconds=None) -> np.ndarray:
    # Chargement mono + rééchantillonnage, partagé entre P2 et P3.
    waveform, sr = _load_raw(path)
    if max_seconds is not None:
        waveform = waveform[:, :int(max_seconds * sr)]   # tronquer AVANT le resample
    if waveform.shape[0] > 1:                            # mono AVANT le resample : ~2x moins
        waveform = waveform.mean(dim=0, keepdim=True)    # d'échantillons à rééchantillonner
    if sr != target_sr:
        waveform = torchaudio.functional.resample(waveform, sr, target_sr)
    return waveform.squeeze().numpy().copy()             # copie : ne pas exposer le tenseur du cache

_P2_PIPES = {}
def p2_get_pipe(model_info: dict):
    # Chargé une seule fois puis réutilisé : évite de re-télécharger/recharger
    # le modèle à chaque identification (gros gain de temps).
    key = model_info['id']
    if key not in _P2_PIPES:
        dev = 0 if torch.cuda.is_available() else -1
        _P2_PIPES[key] = pipeline(model_info['type'], model=key, device=dev)
    return _P2_PIPES[key]

def p2_run_model(model_info: dict, audio_path: str) -> dict:
    try:
        clf = p2_get_pipe(model_info)
        # Chaque modèle attend SON sample rate (CLAP=48k, AST=16k). Décoder à la
        # fréquence du feature extractor évite d'interpréter le signal à la mauvaise
        # vitesse -> genres faussés. Le waveform brut reste mis en cache (_load_raw),
        # seul le rééchantillonnage diffère d'un modèle à l'autre.
        sr = int(getattr(getattr(clf, 'feature_extractor', None), 'sampling_rate', 16000) or 16000)
        audio_np = _to_mono(audio_path, sr, max_seconds=30)
        if model_info['type'] == 'zero-shot-audio-classification':
            # audio déjà décodé au SR du modèle ; le kwarg sampling_rate n'est pas
            # accepté par le pipeline zero-shot selon la version de transformers.
            results = clf(audio_np, candidate_labels=model_info['labels'])
        else:
            results = clf(audio_np, sampling_rate=sr, top_k=5)
        return {
            'success': True,
            'model_name': model_info['name'],
            'description': model_info['description'],
            'top_results': [{'label': r['label'], 'score': r['score']} for r in results[:5]],
            'error': ''
        }
    except Exception as e:
        return {
            'success': False,
            'model_name': model_info['name'],
            'description': model_info.get('description', ''),
            'top_results': [],
            'error': str(e)
        }

def p2_identify_all(audio_path: str, audd_key: str = '', progress_cb=None, models=None) -> dict:
    # `models` : sous-ensemble de P2_MODELS choisi dans l'UI (évite de faire tourner
    # les deux modèles si l'utilisateur n'en veut qu'un — gros gain sur CPU).
    models = models if models is not None else P2_MODELS
    total = 1 + len(models)
    if progress_cb: progress_cb(0, total, '⏳ Identification du titre via AudD.io...')
    title_result = p2_identify_title(audio_path, audd_key)
    if progress_cb: progress_cb(1, total, '✅ Titre traité — analyse des genres...')
    genre_results = []
    for i, model_info in enumerate(models):
        if progress_cb:
            progress_cb(1 + i, total, f'⏳ Modèle {i+1}/{len(models)} : {model_info["name"]}...')
        genre_results.append(p2_run_model(model_info, audio_path))   # décodé au bon SR par modèle
    if progress_cb: progress_cb(total, total, '✅ Analyse complète !')
    return {'title': title_result, 'genres': genre_results}

