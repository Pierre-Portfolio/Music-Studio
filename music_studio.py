def on_s1_download(b):
    with s1_out:
        clear_output()
        url = s1_url.value.strip()
        if not url:
            display(HTML(error_card("Merci d'entrer une URL."))); return
        # Étiquette de source basée sur le hostname réel (et non une sous-chaîne
        # de l'URL brute, qui pouvait mal classer certaines URLs).
        from urllib.parse import urlparse
        _host = (urlparse(url).hostname or '').lower()
        src = '📸 Instagram' if (_host == 'instagram.com' or _host.endswith('.instagram.com')) else '▶️ YouTube'
        display(HTML(info_card(f'⏳ Téléchargement depuis {src}...')))
        res = p1_download(url, s1_fmt.value, s1_cookies.value.strip())
        clear_output()
        if res['success']:
            size_kb = os.path.getsize(res['path']) / 1024
            display(HTML(card(
                f"<b>✅ {src} — {esc(res['title'])}</b><br>"
                f"📁 {esc(os.path.basename(res['path']))} · {size_kb:.0f} KB"
            )))
            if s1_fmt.value in ['mp3', 'wav']:
                display(Audio(res['path']))
            if colab_files:
                colab_files.download(res['path'])
            refresh_dropdowns(res['path'])
        else:
            display(HTML(error_card(res['error'])))

def on_s1_upload(b):
    with s1_out:
        clear_output()
        if colab_files is None:
            display(HTML(error_card("Import local disponible uniquement dans Google Colab."))); return
        display(HTML(info_card('⏳ Sélectionne ton fichier...')))
        uploaded = colab_files.upload()
        if uploaded:
            os.makedirs('./downloads', exist_ok=True)
            for fname, data in uploaded.items():
                safe = os.path.basename(fname)   # neutralise un éventuel path traversal (../)
                dest = f'./downloads/{safe}'
                with open(dest, 'wb') as f:
                    f.write(data)
                display(HTML(card(f'✅ <b>{esc(safe)}</b> importé !')))
                if safe.lower().endswith(('.mp3', '.wav')):   # Audio() ne lit pas un .mp4
                    display(Audio(dest))
                refresh_dropdowns(dest)

