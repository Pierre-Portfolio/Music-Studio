# Cellule 3.3 — Fonctions de génération et assemblage
TARGET_DURATION = 150  # 2min30 en secondes
CHUNK_SIZE = 20        # secondes par chunk (plus grand = moins d'appels generate)

def p3_load_audio_mono(path: str, target_sr: int) -> np.ndarray:
    return _to_mono(path, target_sr)

def p3_save_tmp(audio_np: np.ndarray, sr: int, path: str):
    if audio_np.size == 0:                       # garde : np.max([]) lèverait ValueError
        scipy.io.wavfile.write(path, sr, np.zeros(1, dtype=np.int16))
        return
    norm = (audio_np / (np.max(np.abs(audio_np)) + 1e-9) * 32767).astype(np.int16)
    scipy.io.wavfile.write(path, sr, norm)

def _match_peak(arr: np.ndarray, ref_peak: float) -> np.ndarray:
    # Aligne le pic d'un segment généré sur celui de l'extrait réel : sans ça, une
    # intro/outro plus forte écrase le volume de l'extrait lors de la normalisation
    # finale (qui normalise sur le pic global du mix).
    if arr.size == 0 or ref_peak <= 0:
        return arr
    peak = float(np.max(np.abs(arr)))
    return arr * (ref_peak / peak) if peak > 0 else arr

def p3_crossfade_join(parts, sr, fade=0.05):
    # Fond enchaîné court aux jonctions pour lisser clics et sauts de volume.
    parts = [p for p in parts if len(p) > 0]
    if not parts:
        return np.array([])
    n = max(1, int(sr * fade))
    out = parts[0].astype(np.float32)
    for nxt in parts[1:]:
        nxt = nxt.astype(np.float32)
        m = min(n, len(out), len(nxt))
        if m > 0:
            ramp = np.linspace(0.0, 1.0, m, dtype=np.float32)
            out[-m:] = out[-m:] * (1 - ramp) + nxt[:m] * ramp
            out = np.concatenate([out, nxt[m:]])
        else:
            out = np.concatenate([out, nxt])
    return out

def p3_generate_chunk(context_np: np.ndarray, sr: int, chunk_dur: int, prompt: str = 'music') -> np.ndarray:
    # MusicGen (small) est un modèle texte→musique : on lui fournit un prompt
    # texte ET l'audio de contexte (continuation audio-promptée). `padding=True`
    # est requis quand audio + texte sont combinés.
    max_tokens = int(chunk_dur * p3_model.config.audio_encoder.frame_rate)
    context = context_np[-(sr * 10):]
    inputs = p3_processor(
        audio=context, sampling_rate=sr,
        text=[prompt], padding=True, return_tensors='pt'
    ).to(device)
    if device == 'cuda' and 'input_values' in inputs:
        inputs['input_values'] = inputs['input_values'].half()   # aligne le dtype sur le modèle fp16
    with torch.inference_mode():
        out = p3_model.generate(**inputs, max_new_tokens=max_tokens)
    return out[0, 0].float().cpu().numpy()

def p3_complete_music(audio_path: str, progress_cb=None, prompt: str = 'music') -> dict:
    if not p3_load_model():
        return {'success': False, 'path': '', 'error': 'Impossible de charger le modèle'}

    sr = p3_model.config.audio_encoder.sampling_rate
    os.makedirs('./generated', exist_ok=True)

    try:
        extract = p3_load_audio_mono(audio_path, sr)
        if extract.size == 0:                        # fichier illisible / piste vide
            return {'success': False, 'path': '', 'duration': 0,
                    'error': 'Extrait vide ou illisible (fichier audio invalide ?).'}
        # Si l'extrait dépasse déjà la cible, on le rogne : sinon le fichier de
        # sortie dépasserait les 2min30 annoncés (missing=0 ne tronque rien).
        if len(extract) > int(TARGET_DURATION * sr):
            extract = extract[:int(TARGET_DURATION * sr)]
        extract_dur = len(extract) / sr
        missing = max(0, TARGET_DURATION - extract_dur)

        intro_dur = missing * 0.45
        outro_dur = missing * 0.55
        n_intro = max(0, int(np.ceil(intro_dur / CHUNK_SIZE)))
        n_outro = max(0, int(np.ceil(outro_dur / CHUNK_SIZE)))
        total_steps = n_intro + n_outro

        if progress_cb:
            progress_cb(0, total_steps,
                f'📐 Extrait : {extract_dur:.0f}s → cible : {TARGET_DURATION}s | '
                f'intro : {intro_dur:.0f}s ({n_intro} chunks) | '
                f'outro : {outro_dur:.0f}s ({n_outro} chunks)')

        # --- INTRO ---
        # Un modèle ne génère que "vers l'avant". Pour une intro qui débouche
        # naturellement sur l'extrait, on retourne l'extrait dans le temps, on
        # le prolonge, puis on retourne le résultat (les ÉCHANTILLONS, pas juste
        # l'ordre des blocs). Le contexte reste ancré sur l'audio réel cumulé.
        if n_intro > 0:
            context = extract[::-1].copy()
            intro_chunks = []
            for i in range(n_intro):
                dur = min(CHUNK_SIZE, max(1, int(intro_dur - i * CHUNK_SIZE)))
                if progress_cb:
                    progress_cb(i + 1, total_steps, f'🎵 Intro chunk {i+1}/{n_intro} ({dur}s)...')
                chunk = p3_generate_chunk(context, sr, dur, prompt)
                intro_chunks.append(chunk)
                context = np.concatenate([context, chunk])[-(sr * 10):]   # contexte borné (seule la fin sert à generate)
            intro_audio = np.concatenate(intro_chunks)[::-1].copy()
        else:
            intro_audio = np.array([])

        # --- OUTRO ---
        if n_outro > 0:
            context = extract.copy()
            outro_chunks = []
            for i in range(n_outro):
                dur = min(CHUNK_SIZE, max(1, int(outro_dur - i * CHUNK_SIZE)))
                if progress_cb:
                    progress_cb(n_intro + i + 1, total_steps, f'🎵 Outro chunk {i+1}/{n_outro} ({dur}s)...')
                chunk = p3_generate_chunk(context, sr, dur, prompt)
                outro_chunks.append(chunk)
                context = np.concatenate([context, chunk])[-(sr * 10):]   # contexte borné (seule la fin sert à generate)
            outro_audio = np.concatenate(outro_chunks)
        else:
            outro_audio = np.array([])

        # --- CADRAGE DURÉE : borne intro/outro pour ne pas dépasser la cible ---
        # (le ceil sur le nombre de chunks peut générer un peu plus que prévu ;
        # on garde l'extrait intact et on rogne le surplus généré aux extrémités.)
        if intro_dur > 0 and len(intro_audio) > int(intro_dur * sr):
            intro_audio = intro_audio[-int(intro_dur * sr):]   # garde la fin (près de l'extrait)
        if outro_dur > 0 and len(outro_audio) > int(outro_dur * sr):
            outro_audio = outro_audio[:int(outro_dur * sr)]    # garde le début (près de l'extrait)

        # --- ÉQUILIBRAGE VOLUME : aligne intro/outro sur le pic de l'extrait réel ---
        ref_peak = float(np.max(np.abs(extract))) if extract.size else 0.0
        intro_audio = _match_peak(intro_audio, ref_peak)
        outro_audio = _match_peak(outro_audio, ref_peak)

        # --- ASSEMBLAGE (avec léger crossfade aux jonctions) ---
        full_audio = p3_crossfade_join([intro_audio, extract, outro_audio], sr, fade=0.05)
        # Nom de sortie dérivé du fichier source : évite d'écraser silencieusement
        # le résultat d'un autre morceau déjà complété.
        stem = os.path.splitext(os.path.basename(audio_path))[0]
        out_path = f'./generated/{stem}_completed.wav'
        p3_save_tmp(full_audio, sr, out_path)
        actual_dur = len(full_audio) / sr

        if progress_cb:
            progress_cb(total_steps, total_steps,
                f'✅ Assemblage terminé : {actual_dur:.0f}s ({actual_dur/60:.1f}min)')

        return {'success': True, 'path': out_path, 'duration': actual_dur, 'error': ''}

    except Exception as e:
        return {'success': False, 'path': '', 'duration': 0, 'error': str(e)}

